#!/usr/bin/env bash
# Publish a status document to the orphan branch "site-data":
#   /status.json   the document itself (STATUS CONTRACT, schema 1)
#   /history.json  the last 200 summaries, newest last
#   /vercel.json   disables Vercel deployments for this branch
#   /README.md     what the branch is
#
#   scripts/publish-status.sh build/status.json
#
# Runs in the CI "status" job and locally (to seed the branch). It must run
# inside a clone whose "origin" accepts pushes. The branch is created when
# missing. Concurrent publishers are handled by retrying on a rejected push.
#
# Environment:
#   SITE_DATA_BRANCH  branch name (default site-data)
#   SITE_DATA_DRY_RUN 1 to build the commit without pushing
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <status.json>" >&2; exit 2; }
root=$(git rev-parse --show-toplevel)
status=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
branch=${SITE_DATA_BRANCH:-site-data}
[ -f "$status" ] || { echo "publish-status: $status not found" >&2; exit 1; }
jq -e '.schema == 1 and (.commit | length > 0)' "$status" >/dev/null || { echo "publish-status: $status is not a schema 1 status document with a commit" >&2; exit 1; }
commit=$(jq -r .commit "$status")

# Build the history tool once; the worktree below does not contain Go code.
tooldir=$(mktemp -d)
wt="$tooldir/site-data"
# shellcheck disable=SC2329 # invoked by the EXIT trap
cleanup() {
  git -C "$root" worktree remove --force "$wt" >/dev/null 2>&1 || true
  git -C "$root" branch -D "$branch-new" >/dev/null 2>&1 || true
  rm -rf "$tooldir"
}
trap cleanup EXIT
(cd "$root" && go build -o "$tooldir/reqreport" ./tools/reqreport)

prepare() {
  git -C "$root" worktree remove --force "$wt" >/dev/null 2>&1 || true
  git -C "$root" branch -D "$branch-new" >/dev/null 2>&1 || true
  if git -C "$root" ls-remote --exit-code --heads origin "$branch" >/dev/null 2>&1; then
    git -C "$root" fetch --quiet --depth=1 origin "refs/heads/$branch"
    git -C "$root" worktree add --quiet --detach "$wt" FETCH_HEAD
  else
    echo "publish-status: creating orphan branch $branch"
    git -C "$root" worktree add --quiet --detach "$wt" HEAD
    git -C "$wt" switch --quiet --orphan "$branch-new"
  fi
  cp "$status" "$wt/status.json"
  "$tooldir/reqreport" history -status "$wt/status.json" -history "$wt/history.json"
  cat > "$wt/vercel.json" <<'EOF'
{
  "git": { "deploymentEnabled": false }
}
EOF
  cat > "$wt/README.md" <<EOF
# site-data

Generated by the CI "status" job on every push to main (scripts/publish-status.sh).
Do not edit by hand and do not merge into main.

- \`status.json\`: test, coverage and requirement status for one commit (schema 1)
- \`history.json\`: summaries of the last 200 commits, newest last
- \`agents.json\`: the latest real-agent results (scripts/agents/publish.sh)
- \`workflows.json\`: the latest result of the reference-packages and tap workflows (scripts/publish-workflow-result.sh), read by the status job

The website reads these at build time from
https://raw.githubusercontent.com/ethan03805/Secure-MCP-Gateway/$branch/status.json
EOF
  git -C "$wt" add status.json history.json vercel.json README.md
  if git -C "$wt" rev-parse --verify --quiet HEAD >/dev/null && git -C "$wt" diff --cached --quiet; then
    echo "publish-status: no change for $commit"
    return 1
  fi
  git -C "$wt" -c user.name="github-actions[bot]" -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
    commit --quiet -m "Publish status for ${commit:0:12} [skip ci]" -m "Source: $(jq -r '.runUrl // ""' "$status")"
}

for attempt in 1 2 3 4 5; do
  if ! prepare; then
    exit 0
  fi
  if [ "${SITE_DATA_DRY_RUN:-0}" = 1 ]; then
    echo "publish-status: dry run; commit prepared in $wt:"
    git -C "$wt" show --stat --oneline HEAD | cat
    exit 0
  fi
  if git -C "$wt" push --quiet origin "HEAD:refs/heads/$branch"; then
    echo "publish-status: published status for $commit to $branch"
    exit 0
  fi
  echo "publish-status: push rejected (attempt $attempt); refetching and retrying"
  sleep $((attempt * 2))
done
echo "publish-status: could not publish after 5 attempts" >&2
exit 1
